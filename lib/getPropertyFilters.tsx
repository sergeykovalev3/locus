export function getFilterItemsFromProperties(): FilterItem[] {
  const locations = [...new Set(properties.map((p) => p.adress))].sort().map((adress) => ({
    value: slugify(adress),
    label: adress,
  }));

  const types = [...new Set(properties.map((p) => p.specifications.type))].sort().map((type) => ({
    value: slugify(type),
    label: type,
  }));

  const prices = [...new Set(properties.map((p) => p.price))]
    .sort((a, b) => {
      const numA = parseInt(a.replace(/[^0-9]/g, ''), 10) || 0;
      const numB = parseInt(b.replace(/[^0-9]/g, ''), 10) || 0;
      return numA - numB;
    })
    .map((price) => ({ value: price, label: price }));

  const areas = [...new Set(properties.map((p) => p.specifications.area))]
    .sort((a, b) => a - b)
    .map((area) => ({ value: String(area), label: `${area} sq ft` }));

  return [
    { id: 'location', title: 'Location', icon: locationIcon, options: locations },
    { id: 'propertyType', title: 'Property Type', icon: typeIcon, options: types },
    { id: 'pricingRange', title: 'Pricing Range', icon: priceIcon, options: prices },
    { id: 'propertySize', title: 'Property Size', icon: sizeIcon, options: areas },
    {
      id: 'buildYear',
      title: 'Build Year',
      icon: yearIcon,
      options: [
        { value: '2022', label: '2022' },
        { value: '2023', label: '2023' },
        { value: '2024', label: '2024' },
        { value: '2025', label: '2025' },
      ],
    },
  ];
}
